/** Recipes retain source inputs; parseProjectFile owns every conversion. */
import {readFileSync,writeFileSync} from 'node:fs';
import {parseProjectFile} from '../src/engine/legacyImport';
const root=new URL('../',import.meta.url);
const recipes=JSON.parse(readFileSync(new URL('src/scenes/spirographExamples.recipes.json',root),'utf8'));
const presets=recipes.map((recipe:any)=>{
 const {scene}=parseProjectFile(JSON.stringify(recipe.config));
 if(scene.kind!=='spirograph')throw Error('Spirograph example type mismatch');
 scene.timeline.tracks.forEach((track,index)=>{track.id=`${recipe.id}-track-${index}`;track.actions?.forEach((action,j)=>{action.id=`${track.id}-action-${j}`;});});
 scene.provenance!.reference=recipe.reference;
 scene.provenance!.warnings.push(...recipe.reference.assumptions);
 const {id,name,description,kind,favorite,...document}=scene;
 void id;void name;void description;void kind;void favorite;
 return{id:recipe.id,name:recipe.name,description:recipe.description,document};
});
writeFileSync(new URL('src/scenes/spirographExamples.generated.ts',root),`// Generated by scripts/generate-spirograph-examples.ts. Edit recipes, then regenerate.\nimport type {Preset} from '../types';\nexport const spirographGuideExamples:Preset[]=${JSON.stringify(presets,null,2)};\n`);
console.log(`Generated ${presets.length} complete Spirograph examples`);
