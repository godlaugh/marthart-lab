/** Refresh with the pinned toolchain: node node_modules/vite-node/vite-node.mjs scripts/generate-domain-examples.ts.
 * Recipes retain authored inputs; only parseProjectFile owns their interpretation.
 * The generated complete documents keep runtime scene definitions independent of the importer. */
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {parseProjectFile} from '../src/engine/legacyImport';
const root=new URL('../',import.meta.url);
const recipes=JSON.parse(readFileSync(new URL('src/scenes/domainExamples.recipes.json',root),'utf8'));
const presets=recipes.map((recipe:any)=>{
 const {scene}=parseProjectFile(JSON.stringify(recipe.config));
 if(scene.kind!=='domain')throw new Error('Domain example type mismatch');
 scene.timeline.tracks.forEach((track,index)=>{track.id=`${recipe.id}-track-${index}`;track.actions?.forEach((action,j)=>{action.id=`${track.id}-action-${j}`;});});
 scene.provenance!.reference=recipe.reference;
 scene.provenance!.warnings.push(...recipe.reference.assumptions);
 const {id,name,description,kind,favorite,...document}=scene;
 void id;void name;void description;void kind;void favorite;
 return{id:recipe.id,name:recipe.name,description:recipe.description,document};
});
writeFileSync(new URL('src/scenes/domainExamples.generated.ts',root),`// Generated by scripts/generate-domain-examples.ts. Edit the recipes, then regenerate.\nimport type {Preset} from '../types';\nexport const domainGuideExamples:Preset[]=${JSON.stringify(presets,null,2)};\n`);
console.log(`Generated ${presets.length} complete Domain examples in ${fileURLToPath(root)}src/scenes/domainExamples.generated.ts`);
