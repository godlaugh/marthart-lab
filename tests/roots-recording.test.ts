import {describe,expect,it} from 'vitest';
import type {AnimationAction,AnimationTrack,SceneDocument} from '../src/types';
import {createScene,parseScene,persistentScene} from '../src/engine/document';
import {definition} from '../src/scenes';
import {withRootsPresentation} from '../src/engine/rootsPresentationAuthoring';
import {defaultRootsPresentationConfiguration} from '../src/engine/rootsPresentationConfig';
import {withRootsSceneTimeline} from '../src/engine/rootsCameraTimeline';
import {rootsSampleProgressAt,rootsSchedule} from '../src/scenes/rootsDensity';
import {
 isRootsAutoRecordingComplete,prepareRootsOrdinalCompletion,withRootsFreshRecording,planRootsFreshRecording,
 RootsRecordingError,type RootsAutoRecordingInputs,
} from '../src/engine/rootsRecording';

const base:RootsAutoRecordingInputs={queueComplete:true,hasAnimations:false,mode:'density',finishedWorkers:2,workerCount:2,queueSize:0,pendingPoints:0};
const clip=(id:string,duration:number,actions?:AnimationAction[]):AnimationTrack=>({id,type:actions?'animate':'wait',target:actions?'camera.actions':'timeline.wait',from:0,to:0,start:0,duration,easing:'linear',enabled:true,pingPong:false,...(actions?{actions}:{})});
function scene(tracks:AnimationTrack[]=[],samples=100,workers=3):SceneDocument {
 const s=withRootsSceneTimeline(withRootsPresentation(createScene(definition('roots')),defaultRootsPresentationConfiguration()),true);
 s.rootsMath!.sampling={...s.rootsMath!.sampling,sampleCount:samples,workerCount:workers,seed:'-9223372036854775808'};
 s.settings={...s.settings,rootSamplesPerFrame:10,rootSamplingFps:4,rootStartTime:0};
 s.timeline={...s.timeline,tracks,fps:4,duration:10};return s;
}
const options={simulationFps:4,encoderFps:24};
const gradient:AnimationAction={id:'gradient',method:'gradientStart',gradient:{mode:'hue_rotate',interpolation:'linear',speed:360}};

describe('retained source automatic recording completion predicate',()=>{
 // Static source truth table, not a result generated by the scene clock.
 it.each([
  ['incomplete manager', {queueComplete:false},false],
  ['completed nonempty manager ignores unfinished workers',{hasAnimations:true,finishedWorkers:0,queueSize:100,pendingPoints:100},true],
  ['empty manager requires all workers',{finishedWorkers:1},false],
  ['empty manager requires submitted queue empty',{queueSize:1},false],
  ['density requires pending points empty',{pendingPoints:1},false],
  ['cloud does not consult pending points',{mode:'point-cloud',pendingPoints:1},true],
  ['all synchronous submissions completed',{},true],
  ['source max(1,W)',{workerCount:0,finishedWorkers:0},false],
  ['source worker lower bound completed',{workerCount:0,finishedWorkers:1},true],
  ['source counters compare <=0',{queueSize:-1,pendingPoints:-1},true],
 ] as const)('%s',(_label,delta,expected)=>expect(isRootsAutoRecordingComplete({...base,...delta})).toBe(expected));
 it('keeps source short-circuit ownership: completed animations do not inspect worker or mode facts',()=>{
  expect(isRootsAutoRecordingComplete({...base,hasAnimations:true,workerCount:NaN,queueSize:NaN,mode:'unobserved' as never})).toBe(true);
  expect(isRootsAutoRecordingComplete({...base,queueComplete:false,hasAnimations:true,workerCount:NaN})).toBe(false);
  expect(()=>isRootsAutoRecordingComplete({...base,finishedWorkers:NaN})).toThrow(RootsRecordingError);
  expect(()=>isRootsAutoRecordingComplete({...base,mode:'other' as never})).toThrow(RootsRecordingError);
 });
});

describe('one ordinal completion observer owns worker partition facts',()=>{
 it('uses the retained balanced partition boundaries, without treating an in-progress worker as finished',()=>{
  // N10/W3 -> [0..3], [4..6], [7..9], independently hand-derived.
  const p=prepareRootsOrdinalCompletion(10,3,'0');
  expect([0,1,3,4,6,7,9,10].map(n=>p.at(n,'density',true,false).finishedWorkers)).toEqual([0,0,0,1,1,2,2,3]);
  expect(p.at(9,'density',true,false).complete).toBe(false);
  expect(p.at(10,'density',true,false)).toMatchObject({complete:true,policy:'local-synchronous-ordinal',queueSize:0,pendingPoints:0});
  expect(p.at(0,'density',true,true).complete).toBe(true);
  expect(p.at(10,'point-cloud',false,false).complete).toBe(false);
 });
 it('uses the actual worker field min(N,configuredW), preserving its authored source separately',()=>{
  const p=prepareRootsOrdinalCompletion(2,20,'9223372036854775807');
  expect(p).toMatchObject({workerCount:2,configuredWorkerCount:20});
  expect(p.at(1,'point-cloud',true,false)).toMatchObject({finishedWorkers:1,complete:false});
  expect(p.at(2,'point-cloud',true,false)).toMatchObject({finishedWorkers:2,complete:true});
 });
 it('retains constant-size lazy ownership even at the source signed-int sample/worker limit',()=>{
  const p=prepareRootsOrdinalCompletion(2147483647,2147483647,'-9223372036854775808');
  expect(p.at(2147483646,'density',true,false).finishedWorkers).toBe(2147483646);
  expect(p.at(2147483647,'density',true,false).complete).toBe(true);
  const first=p.at(0,'density',true,false);expect(Object.isFrozen(first)).toBe(true);
  p.at(2147483647,'density',true,false);expect(first.finishedWorkers).toBe(0);
 });
 it.each([-1,.5,11,NaN,Infinity])('rejects malformed or out-of-range attempted count %s',n=>{
  expect(()=>prepareRootsOrdinalCompletion(10,2,'0').at(n,'density',true,false)).toThrow(RootsRecordingError);
 });
 it.each([[0,1,'0'],[1,0,'0'],[1,1,'9223372036854775808'],[1,1,' 1'],[1,1,'1e2']] as const)('rejects invalid source partition/seed input %s/%s/%s',(n,w,seed)=>{
  expect(()=>prepareRootsOrdinalCompletion(n,w,seed)).toThrow(RootsRecordingError);
 });
 it('does not coerce a transport number seed into an exact source long',()=>{
  expect(()=>prepareRootsOrdinalCompletion(1,1,1 as never)).toThrow(expect.objectContaining({code:'input'}));
 });
});

describe('fresh replay recording plan uses the actual source frame queue',()=>{
 it('performs one warmup and allows zero encoded frames for a short nonempty queue',()=>{
  const p=planRootsFreshRecording(scene([clip('short',.001)]),options);
  expect(p).toMatchObject({policy:'fresh-local-ordinal-replay',updates:1,encodedFrames:0,firstEncodedUpdate:null,lastDisplayFrame:0,completionReason:'animation-queue',warmupUpdates:1});
  expect(p.completion).toMatchObject({attemptedSamples:10,finishedWorkers:0,complete:true});
 });
 it('does not carry a short clip remainder into the next clip or force an extra end frame',()=>{
  const p=planRootsFreshRecording(scene([clip('a',.01),clip('b',.01)]),options);
  expect(p).toMatchObject({updates:2,encodedFrames:1,firstEncodedUpdate:2,lastDisplayFrame:1});
  expect(p.finalFrame).toMatchObject({finishedClip:1,queueIndex:2,queueComplete:true});
 });
 it.each([[24,2],[30,2],[60,2],[120,4]])('keeps short-clip completion on discrete %s-FPS updates',(simulationFps,updates)=>{
  // At <=60 FPS each .01-s clip finishes in one update, without carry.
  // At 120 FPS each needs two .00833-s updates. Encoding discards update 1.
  const p=planRootsFreshRecording(scene([clip('a',.01),clip('b',.01)]),{simulationFps,encoderFps:30});
  expect(p.updates).toBe(updates);expect(p.encodedFrames).toBe(updates-1);
 });
 it('finishes a running gradient at queue completion, not when gradient or samples stop',()=>{
  const p=planRootsFreshRecording(scene([clip('start',1,[gradient])]),options);
  expect(p).toMatchObject({updates:4,encodedFrames:3,completionReason:'animation-queue'});
  expect(p.finalFrame.gradient).toMatchObject({running:true,offset:.25,speedScale:1});
  expect(p.completion.attemptedSamples).toBe(40);expect(p.completion.finishedWorkers).toBe(1);
 });
 it('waits for empty-queue ordinal sampling rather than timeline.duration',()=>{
  const s=scene();s.timeline.duration=1;
  const p=planRootsFreshRecording(s,options);
  expect(p).toMatchObject({updates:10,encodedFrames:9,lastDisplayFrame:9,completionReason:'ordinal-samples'});
  expect(p.completion).toMatchObject({attemptedSamples:100,workerCount:3,finishedWorkers:3,complete:true});
 });
 it('applies the same empty-queue contract to both density and point cloud with a delayed local schedule',()=>{
  const density=scene([],20,20);density.settings.rootStartTime=.5;
  const cloud=structuredClone(density);cloud.rootsPresentation!.mode='point-cloud';
  for(const s of[density,cloud]){
   const p=planRootsFreshRecording(s,options);
   expect(p).toMatchObject({updates:4,encodedFrames:3,lastDisplayFrame:3});
   expect(p.completion).toMatchObject({attemptedSamples:20,finishedWorkers:20,complete:true,queueSize:0,pendingPoints:0});
  }
 });
 it('supports a zero-output empty queue when all samples submit in warmup',()=>{
  const p=planRootsFreshRecording(scene([],2,20),options);
  expect(p).toMatchObject({updates:1,encodedFrames:0,firstEncodedUpdate:null,logicalWorkerCount:2});
 });
 it('treats disabled/unsupported tracks as absent manager children and retains warnings',()=>{
  const disabled=clip('disabled',100);disabled.enabled=false;
  const other={...clip('other',100),type:'numeric' as const,target:'settings.rootSourceBrightness',from:1,to:2};
  const p=planRootsFreshRecording(scene([disabled,other],20),options);
  expect(p).toMatchObject({updates:2,completionReason:'ordinal-samples'});expect(p.warnings.join('\n')).toContain('numeric');
 });
 it('keeps simulation and encoder rates independent and does not mutate authored baseline',()=>{
  const s=scene([clip('wait',1)]),before=structuredClone(s);
  const slow=planRootsFreshRecording(s,{simulationFps:2,encoderFps:120}),fast=planRootsFreshRecording(s,{simulationFps:4,encoderFps:1});
  expect(slow).toMatchObject({updates:2,encodedFrames:1,simulationFps:2,encoderFps:120});
  expect(fast).toMatchObject({updates:4,encodedFrames:3,simulationFps:4,encoderFps:1});
  expect(planRootsFreshRecording(s,{simulationFps:4,encoderFps:120}).finalFrame).toEqual(fast.finalFrame);
  const fresh=withRootsFreshRecording(s,2);expect(fresh.timeline.fps).toBe(2);expect(s).toEqual(before);
  expect({...fresh,timeline:{...fresh.timeline,fps:s.timeline.fps}}).toEqual(s);
  expect(planRootsFreshRecording(parseScene(JSON.stringify(persistentScene(s))),options)).toEqual(planRootsFreshRecording(s,options));
 });
 it.each([0,.5,121,NaN,Infinity])('rejects simulation FPS %s before planning',simulationFps=>{
  expect(()=>planRootsFreshRecording(scene(),{simulationFps,encoderFps:30})).toThrow();
 });
 it.each([0,1.5,121,NaN,Infinity])('rejects encoder FPS %s',encoderFps=>{
  expect(()=>planRootsFreshRecording(scene(),{simulationFps:4,encoderFps})).toThrow(RootsRecordingError);
 });
 it('does not silently upgrade omitted/local presentation, math, color, or timeline profiles',()=>{
  const s=scene(),cases=[structuredClone(s),structuredClone(s),structuredClone(s),structuredClone(s),structuredClone(s)];
  delete cases[0].timeline.schedule;cases[1].rootsPresentation!.model='local-v1';cases[2].rootsMath!.model='local-v1';
  delete cases[3].settings.rootDensityColorVersion;cases[4].settings.rootsMode='single';
  for(const value of cases)expect(()=>planRootsFreshRecording(value,options)).toThrow(RootsRecordingError);
 });
 it('retains camera-only queue semantics without activating stored gradient actions',()=>{
  const s=scene([clip('old',1,[gradient])]);s.timeline.schedule='roots-camera-sequence-v1';
  const p=planRootsFreshRecording(s,options);expect(p.finalFrame).not.toHaveProperty('gradient');expect(p.encodedFrames).toBe(3);
 });
 it('cancels before work and during replay without retaining partial state or changing the input',()=>{
  const s=scene([clip('wait',10)]),before=structuredClone(s);let calls=0;
  expect(()=>planRootsFreshRecording(s,{...options,isCancelled:()=>true})).toThrow(expect.objectContaining({name:'AbortError'}));
  expect(()=>planRootsFreshRecording(s,{...options,isCancelled:()=>++calls===20})).toThrow(expect.objectContaining({name:'AbortError'}));
  const userError=new Error('caller callback');expect(()=>planRootsFreshRecording(s,{...options,isCancelled:()=>{throw userError;}})).toThrow(userError);
  expect(s).toEqual(before);expect(planRootsFreshRecording(s,options).updates).toBe(40);
 });
 it('enforces shared per-request queue-fold work rather than guessing a closed-form duration',()=>{
  const s=scene(Array.from({length:1000},(_,i)=>clip(String(i),86400)));
  expect(()=>planRootsFreshRecording(s,options)).toThrow(expect.objectContaining({code:'capacity'}));
 });
});

describe('shared prepared ordinal schedule lookup',()=>{
 it('preserves the previous operation order and pre-start negative frame semantics',()=>{
  const s=scene([],25);s.settings.rootStartTime=1;const schedule=rootsSchedule(s.settings,s.rootsMath);
  expect([0,.75,1,1.25,1.5,100].map(t=>rootsSampleProgressAt(schedule,t))).toEqual([
   {frame:-4,attemptedSamples:0},{frame:-1,attemptedSamples:0},{frame:0,attemptedSamples:10},
   {frame:1,attemptedSamples:20},{frame:2,attemptedSamples:25},{frame:2,attemptedSamples:25},
  ]);
  expect(rootsSampleProgressAt(schedule,1.25-1e-12)).toEqual({frame:1,attemptedSamples:20});
  expect(rootsSampleProgressAt(schedule,1.25-1e-8)).toEqual({frame:0,attemptedSamples:10});
 });
});
